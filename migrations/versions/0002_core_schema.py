VIEWS_SQL = f"""
CREATE VIEW v_documents AS
SELECT d.id                        AS document_id,
       d.name                      AS document_name,
       d.document_type,
       d.document_type_confidence,
       d.mime_type,
       d.status,
       d.version,
       d.source,
       d.drive_file_id,
       d.web_view_link,
       d.search_indexed,
       d.attempts,
       d.last_error,
       d.drive_modified_at,
       d.processed_at,
       d.created_at
FROM documents d
WHERE {_VISIBLE_DOC};

CREATE VIEW v_funds AS
SELECT f.id              AS fund_id,
       f.canonical_name  AS fund_name,
       f.manager,
       f.strategy,
       f.currency,
       COALESCE((SELECT array_agg(a.alias ORDER BY a.alias) FROM fund_aliases a WHERE a.fund_id = f.id), '{{}}'::text[]) AS aliases,
       EXISTS (SELECT 1 FROM fund_aliases a WHERE a.fund_id = f.id AND NOT a.confirmed AND a.match_method = 'fuzzy') AS has_unconfirmed_alias
FROM funds f;

CREATE VIEW v_accounts AS
SELECT ac.id                     AS account_id,
       ac.canonical_name         AS account_name,
       ac.account_number_masked,
       ac.custodian,
       ac.currency,
       COALESCE((SELECT array_agg(a.alias ORDER BY a.alias) FROM account_aliases a WHERE a.account_id = ac.id), '{{}}'::text[]) AS aliases,
       EXISTS (SELECT 1 FROM account_aliases a WHERE a.account_id = ac.id AND NOT a.confirmed AND a.match_method = 'fuzzy') AS has_unconfirmed_alias
FROM accounts ac;

CREATE VIEW v_returns AS
SELECT r.id                                       AS return_id,
       r.fund_id,
       f.canonical_name                           AS fund_name,
       f.manager,
       f.strategy,
       f.currency                                 AS fund_currency,
       r.period_end,
       EXTRACT(YEAR FROM r.period_end)::int       AS period_year,
       EXTRACT(MONTH FROM r.period_end)::int      AS period_month,
       r.period_label,
       r.return_type,
       r.net_gross,
       r.value,
       r.value * 100                              AS value_pct,
       r.status,
       r.review_reasons,
       r.confidence,
       r.page,
       r.source_snippet,
       d.id                                       AS document_id,
       d.name                                     AS document_name,
       d.document_type
FROM returns r
JOIN funds f     ON f.id = r.fund_id
JOIN documents d ON d.id = r.document_id
WHERE {_VISIBLE_DOC};

CREATE VIEW v_fund_facts AS
SELECT ff.id              AS fact_id,
       ff.fund_id,
       f.canonical_name   AS fund_name,
       f.manager,
       f.strategy,
       ff.name            AS metric,
       ff.value,
       ff.value_text,
       ff.unit,
       ff.as_of_date,
       ff.status,
       ff.review_reasons,
       ff.confidence,
       ff.page,
       ff.source_snippet,
       d.id               AS document_id,
       d.name             AS document_name,
       d.document_type
FROM fund_facts ff
JOIN funds f     ON f.id = ff.fund_id
JOIN documents d ON d.id = ff.document_id
WHERE {_VISIBLE_DOC};

CREATE VIEW v_statements AS
SELECT s.id                      AS statement_id,
       s.account_id,
       ac.canonical_name         AS account_name,
       ac.account_number_masked,
       ac.custodian,
       s.fund_id,
       f.canonical_name          AS fund_name,
       f.manager,
       s.period_start,
       s.period_end,
       s.opening_balance,
       s.contributions,
       s.withdrawals,
       s.pnl,
       s.fees,
       s.closing_balance,
       s.currency,
       s.status,
       s.review_reasons,
       (SELECT count(*) FROM statement_holdings h WHERE h.statement_id = s.id)::int AS holdings_count,
       d.id                      AS document_id,
       d.name                    AS document_name,
       d.document_type
FROM statements s
JOIN accounts ac     ON ac.id = s.account_id
LEFT JOIN funds f    ON f.id = s.fund_id
JOIN documents d     ON d.id = s.document_id
WHERE {_VISIBLE_DOC};

CREATE VIEW v_holdings AS
SELECT h.id                AS holding_id,
       h.statement_id,
       s.account_id,
       ac.canonical_name   AS account_name,
       ac.custodian,
       s.fund_id,
       f.canonical_name    AS fund_name,
       s.period_end,
       s.currency,
       h.line_no,
       h.name              AS holding_name,
       h.identifier,
       h.quantity,
       h.market_value,
       h.weight,
       h.weight * 100      AS weight_pct,
       h.status,
       h.review_reasons,
       h.confidence,
       h.page,
       h.source_snippet,
       d.id                AS document_id,
       d.name              AS document_name
FROM statement_holdings h
JOIN statements s    ON s.id = h.statement_id
JOIN accounts ac     ON ac.id = s.account_id
LEFT JOIN funds f    ON f.id = s.fund_id
JOIN documents d     ON d.id = s.document_id
WHERE {_VISIBLE_DOC};

-- Internal (NOT granted to app_readonly): one row per open review item for /api/review.
CREATE VIEW review_queue AS
SELECT 'returns:' || r.id AS item_key, 'returns'::text AS target_table, r.id AS target_id,
       r.status, r.review_reasons, r.review_detail, r.document_id, d.name AS document_name,
       r.fund_id, NULL::bigint AS account_id, r.created_at
FROM returns r JOIN documents d ON d.id = r.document_id
WHERE r.status <> 'ok' AND {_VISIBLE_DOC}
UNION ALL
SELECT 'fund_facts:' || ff.id, 'fund_facts', ff.id,
       ff.status, ff.review_reasons, ff.review_detail, ff.document_id, d.name,
       ff.fund_id, NULL::bigint, ff.created_at
FROM fund_facts ff JOIN documents d ON d.id = ff.document_id
WHERE ff.status <> 'ok' AND {_VISIBLE_DOC}
UNION ALL
SELECT 'statements:' || s.id, 'statements', s.id,
       s.status, s.review_reasons, s.review_detail, s.document_id, d.name,
       s.fund_id, s.account_id, s.created_at
FROM statements s JOIN documents d ON d.id = s.document_id
WHERE s.status <> 'ok' AND {_VISIBLE_DOC}
UNION ALL
SELECT 'statement_holdings:' || h.id, 'statement_holdings', h.id,
       h.status, h.review_reasons, h.review_detail, s.document_id, d.name,
       s.fund_id, s.account_id, h.created_at
FROM statement_holdings h JOIN statements s ON s.id = h.statement_id JOIN documents d ON d.id = s.document_id
WHERE h.status <> 'ok' AND {_VISIBLE_DOC}
UNION ALL
SELECT 'fund_aliases:' || a.id, 'fund_aliases', a.id,
       'needs_review'::text, ARRAY['alias_match']::text[],
       jsonb_build_object('alias', a.alias, 'match_score', a.match_score, 'fund_id', a.fund_id),
       a.source_document_id, d.name, a.fund_id, NULL::bigint, a.created_at
FROM fund_aliases a LEFT JOIN documents d ON d.id = a.source_document_id
WHERE a.match_method = 'fuzzy' AND NOT a.confirmed
UNION ALL
SELECT 'account_aliases:' || a.id, 'account_aliases', a.id,
       'needs_review'::text, ARRAY['alias_match']::text[],
       jsonb_build_object('alias', a.alias, 'match_score', a.match_score, 'account_id', a.account_id),
       a.source_document_id, d.name, NULL::bigint, a.account_id, a.created_at
FROM account_aliases a LEFT JOIN documents d ON d.id = a.source_document_id
WHERE a.match_method = 'fuzzy' AND NOT a.confirmed;
"""

