def _in(col: str, values: tuple[str, ...]) -> str:
    return f"{col} IN ({', '.join(repr(v) for v in values)})"


_REASONS_ARRAY = "ARRAY[" + ", ".join(repr(r) for r in REVIEW_REASONS) + "]::text[]"


def _review_cols() -> str:
    return """
    status          text NOT NULL DEFAULT 'ok',
    review_reasons  text[] NOT NULL DEFAULT '{}'::text[],
    review_detail   jsonb"""


def _review_checks(t: str) -> str:
    return f"""
    CONSTRAINT ck_{t}_status CHECK ({_in("status", ("ok", "needs_review", "conflict"))}),
    CONSTRAINT ck_{t}_review_reasons CHECK (review_reasons <@ {_REASONS_ARRAY}),
    CONSTRAINT ck_{t}_status_reasons CHECK ((status = 'ok') = (cardinality(review_reasons) = 0)),
    CONSTRAINT ck_{t}_conflict_reason CHECK ((status = 'conflict') = ('conflict' = ANY(review_reasons)))"""


def _conf_page_checks(t: str) -> str:
    return f"""
    CONSTRAINT ck_{t}_confidence CHECK (confidence IS NULL OR (confidence >= 0 AND confidence <= 1)),
    CONSTRAINT ck_{t}_page CHECK (page IS NULL OR page >= 1)"""


