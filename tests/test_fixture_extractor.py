COMMITTED = sorted(FIXTURES_DIR.glob("*.json")) if FIXTURES_DIR.is_dir() else []


def test_loads_and_validates_fixture(tmp_path):
    ex = make_extraction()
    write_fixture(tmp_path, "a.pdf", b"bytes", ex, input_tokens=11, output_tokens=22)
    r = FixtureExtractor(tmp_path).extract_with_meta(b"bytes", "application/pdf", name="a.pdf")
    assert r.extraction == ex
    assert r.source == "fixture" and r.model == "claude-opus-5-5"
    assert (r.input_tokens, r.output_tokens) == (11, 22)


def test_name_is_used_without_directories(tmp_path):
    write_fixture(tmp_path, "a.pdf", b"x", make_extraction())
    assert FixtureExtractor(tmp_path).extract_with_meta(b"x", "application/pdf", name="sub/a.pdf").extraction


def test_md5_mismatch_still_loads(tmp_path):
    write_fixture(tmp_path, "a.pdf", b"old", make_extraction())
    assert FixtureExtractor(tmp_path).extract_with_meta(b"new", "application/pdf", name="a.pdf").extraction


def test_missing_fixture_is_permanent(tmp_path):
    with pytest.raises(PermanentExtractionError, match="no fixture"):
        FixtureExtractor(tmp_path).extract_with_meta(b"x", "application/pdf", name="new.pdf")
    with pytest.raises(PermanentExtractionError):
        FixtureExtractor(tmp_path).extract_with_meta(b"x", "application/pdf")


@pytest.mark.parametrize("body", ["not json", json.dumps({"fixture_format": 99, "extraction": {}}),
                                  json.dumps({"fixture_format": 1, "extraction": {"document_type": "nope"}})])
def test_invalid_fixtures_are_permanent(tmp_path, body):
    (tmp_path / "a.pdf.json").write_text(body)
    with pytest.raises(PermanentExtractionError):
        FixtureExtractor(tmp_path).extract_with_meta(b"x", "application/pdf", name="a.pdf")


